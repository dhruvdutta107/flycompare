-- FlyCompare schema for Supabase (PostgreSQL). Idempotent: safe to run on every start-up.
-- The Express server connects with the database connection string, so it bypasses Row Level Security.
-- RLS stays ON with no policies and the API roles get no table privileges, so nothing is readable through
-- Supabase's public REST/GraphQL API with the anon/publishable key.

create table if not exists public.users (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text not null unique,
  password_hash text not null,
  created_at    timestamptz not null default now()
);
create unique index if not exists users_email_lower_idx on public.users (lower(email));

create table if not exists public.sessions (
  token_hash text primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  expires_at bigint not null,                       -- epoch milliseconds
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  token           text primary key,
  pnr             text unique,
  user_id         bigint references public.users(id) on delete set null,
  status          text not null check (status in ('held','confirmed','cancelled','expired')),
  trip_type       text not null,
  cabin           text not null,
  adults          integer not null,
  children        integer not null,
  infants         integer not null,
  legs_json       jsonb not null,
  passengers_json jsonb,
  contact_email   text,
  contact_phone   text,
  base_amount     integer not null,
  taxes           integer not null,
  discount        integer not null default 0,
  total           integer not null,
  promo_code      text,
  payment_json    jsonb,
  pay_attempts    integer not null default 0,
  refund_amount   integer,
  created_at      timestamptz not null default now(),
  expires_at      bigint not null,                  -- epoch milliseconds (fare hold)
  confirmed_at    timestamptz,
  cancelled_at    timestamptz
);
create index if not exists idx_bookings_user  on public.bookings (user_id, created_at);
create index if not exists idx_bookings_email on public.bookings (contact_email);

create table if not exists public.support_tickets (
  id         bigint generated by default as identity primary key,
  name       text not null,
  email      text not null,
  message    text not null,
  user_id    bigint references public.users(id) on delete set null,
  status     text not null default 'open',
  created_at timestamptz not null default now()
);

create table if not exists public.reminders (
  id             bigint generated by default as identity primary key,
  booking_token  text not null references public.bookings(token) on delete cascade,
  kind           text not null check (kind in ('checkin','leave','custom')),
  leg_index      integer not null default 0,
  minutes_before integer not null,
  remind_at      bigint not null,                   -- epoch milliseconds
  created_at     timestamptz not null default now()
);
create index if not exists idx_reminders_booking on public.reminders (booking_token);

-- Lock the tables away from Supabase's public Data API: only the server (postgres role) may use them.
alter table public.users           enable row level security;
alter table public.sessions        enable row level security;
alter table public.bookings        enable row level security;
alter table public.support_tickets enable row level security;
alter table public.reminders       enable row level security;
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on public.users, public.sessions, public.bookings, public.support_tickets, public.reminders from anon, authenticated;
  end if;
end $$;
